"""report2.md and summary_PL2.md, generated from results2/summary and results2/merged/*_status.json only.

    python -m analysis2.report
"""
import glob
import json
import os

import numpy as np
import pandas as pd

from analysis2.common import SUMMARY

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MERGED = os.path.join(ROOT, "results2", "merged")


def f3(v):
    return "—" if v is None or not np.isfinite(v) else f"{v:.3f}"


def ci(r, c):
    """'0.192 (0.192–0.193)' or '—' when not reached."""
    if not np.isfinite(r[c]):
        return "—"
    lo, hi = r.get(c + "_lo", np.nan), r.get(c + "_hi", np.nan)
    return f3(r[c]) + (f" ({f3(lo)}–{f3(hi)})" if np.isfinite(lo) and np.isfinite(hi) else " (CI open)")


def opposite(cells, side):
    """Cells whose 95 % CI lies entirely on the side opposite to the prediction."""
    return sum(c["ci"][1] < side if side == 1 else c["ci"][0] > side for c in cells)


def main():
    H = json.load(open(os.path.join(SUMMARY, "hypotheses.json")))
    V = {k: v["verdict"] for k, v in H.items()}
    tg = pd.read_csv(os.path.join(SUMMARY, "thresholds_gauss.csv"))
    tp = pd.read_csv(os.path.join(SUMMARY, "thresholds_population.csv"))
    conv = pd.read_csv(os.path.join(SUMMARY, "convergence.csv"))
    st = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(MERGED, "*_status.json")))]
    n_jobs, n_fail = sum(s["done"] for s in st), sum(len(s["failed"]) for s in st)
    gpu_h = sum(s["gpu_hours"] for s in st)
    prereg = open(os.path.join(ROOT, "PREREGISTRATION.md")).read()
    deviations = prereg.split("## Deviations", 1)[1].strip()

    g = tg[(tg.m == 4) & (tg.belief == "S2")].set_index(["type", "basis", "k"])
    p = tp[(tp.m == 4) & (tp.belief == "S2")].set_index(["type", "basis", "k"])
    L = []
    w = L.append
    w("# Constant-denominator approximation in HCR neurons at high input dimension\n")
    w(f"*All numbers are generated by `analysis2/report.py` from `results2/summary/` "
      f"({n_jobs} jobs, {n_fail} failed, {gpu_h:.1f} GPU-h of job time on A100).*\n")
    w("## Setup")
    w("- One HCR neuron with k inputs, k ∈ {2, 4, 8, 16, 32}, orthonormal Legendre basis of degree m ∈ {2, 4, 6}, "
      "\"pair\" (marginals + pairwise x–y_i terms) or \"triple\" (+ x–y_i–y_j) basis; coefficients by moment estimation "
      "from n_est = 1e7 samples (50 seeds) or exactly from the population.")
    w("- Ground truth: Gaussian copula with exchangeable inputs of Spearman ρ_S (SUM and CONTRAST neuron types); "
      "also t3, t10, Clayton, Gumbel at matched Kendall τ, and LKJ random correlation matrices.")
    w("- CONST_DENOM = E_q[N]/E_q[D] (paper Eq. 10) is compared with EXACT_UNCAL = E_q[N/D] (defined only while D ≥ 0.01 "
      "on supp q), EXACT_CAL (clipped, renormalised) and GOLD (analytic conditional); d_denom = TV(CONST_DENOM, EXACT_UNCAL).")
    w("- Beliefs q: S2 flat (headline), S3a–d Beta products, S4 the true input copula; MC with 2^20 samples, 16 replicates.")
    w("- Stage 4: chains of L ≤ 4 neurons (k ≤ 8, 10 seeds), with value, likelihood and end-to-end training (Adam, L-BFGS).")
    w("- Hypotheses, decision rules and grids were frozen in `PREREGISTRATION.md` before any production job.\n")

    w("## Thresholds (belief S2, m = 4; ρ_S at which the level is first reached, 95 % bootstrap CI over seeds)")
    w("\"—\": not reached before EXACT_UNCAL becomes undefined (D < 0) or by ρ_S = 0.9. Onset = ρ_S where min D crosses 0.\n")
    w("| type | basis | k | d_denom ≥ 1 % | d_denom ≥ 5 % | D < 0 onset (n_est = 1e7) | D < 0 onset (population) | undefined from |")
    w("|---|---|---|---|---|---|---|---|")
    for typ in ("SUM", "CONTRAST"):
        for basis in ("pair", "triple"):
            for k in (2, 4, 8, 16, 32):
                r, q = g.loc[(typ, basis, k)], p.loc[(typ, basis, k)]
                w(f"| {typ} | {basis} | {k} | {ci(r, 'denom_1pct')} | {ci(r, 'denom_5pct')} | {ci(r, 'neg_onset')} | "
                  f"{f3(q.neg_onset)} | {f3(r.undef_onset)} |")
    w("")

    # Q1
    h1b = {(c["type"], c["basis"]): c for c in H["H1b"]["cells"]}
    sp = h1b[("SUM", "pair")]
    h1c = H["H1c"]["cells"]
    w("## Answers")
    w(f"**Q1 – input dimension.** H1a (population onsets fall with k): **{V['H1a']}** "
      f"({H['H1a']['significant']}/{len(H['H1a']['cells'])} cells strictly decreasing). "
      f"H1b (same with n_est = 1e7): **{V['H1b']}** ({H['H1b']['significant']}/{len(H['H1b']['cells'])}); "
      f"SUM/pair onset {f3(sp['onset_k2'])} at k = 2 vs {f3(sp['onset_k32'])} at k = 32 "
      f"(difference CI {f3(sp['ci'][0])} to {f3(sp['ci'][1])}). "
      f"At k = 32 the finite-sample onset ({f3(g.loc[('SUM', 'pair', 32)].neg_onset)}) is earlier than the population one "
      f"({f3(p.loc[('SUM', 'pair', 32)].neg_onset)}): estimation noise alone makes D negative sooner. "
      f"H1c (d_denom a single power law of the distance χ_D of D from flat): **{V['H1c']}**; share of points within "
      f"a factor 2: " + ", ".join(f"{c['type']}/{c['basis']} {c['within2']:.2f}" for c in h1c) + ".\n")
    # Q2
    w(f"**Q2 – basis.** H2a (onset earlier for higher m): **{V['H2a']}** ({H['H2a']['significant']}/"
      f"{len(H['H2a']['cells'])}). H2b (triple earlier than pair): **{V['H2b_population']}** with population "
      f"coefficients ({H['H2b_population']['significant']}/{len(H['H2b_population']['cells'])}) and **{V['H2b_gauss']}** "
      f"with n_est = 1e7 ({H['H2b_gauss']['significant']}/{len(H['H2b_gauss']['cells'])}). H2c (d_denom changes by "
      f"≤ 1.5× across m): **{V['H2c']}** ({H['H2c']['share']:.0%} of {H['H2c']['n']} points; supported needs ≥ 80 %).\n")
    # Q3
    c3 = pd.DataFrame(H["H3a"]["cells"])
    fam = c3.groupby("family").agg(n=("diff", "size"), lo=("diff", "min"), hi=("diff", "max"),
                                   inside=("inside", "sum"), outside=("outside", "sum"))
    b3 = pd.DataFrame(H["H3b"]["cells"]).groupby("family").ratio.median()
    h3c = {c["basis"]: c for c in H["H3c"]["cells"]}
    w(f"**Q3 – ground truth.** H3a (onset within ±0.05 of the Gaussian): **{V['H3a']}**: "
      f"{H['H3a']['n_inside']}/{H['H3a']['n']} CIs inside, {H['H3a']['n_outside']} entirely outside. "
      f"H3b (d_denom within a factor 2 of the Gaussian): **{V['H3b']}** ({H['H3b']['n_inside']}/{H['H3b']['n']} inside, "
      f"{H['H3b']['n_outside']} outside). H3c (the Gaussian power law predicts LKJ d_denom within a factor 2 for ≥ 80 %): "
      f"**{V['H3c']}** (pair {h3c['pair']['within2']:.0%}, triple {h3c['triple']['within2']:.0%} of {h3c['pair']['n']} "
      f"defined matrices); for k ≥ 4 no LKJ matrix leaves EXACT_UNCAL defined, so H3c rests on k = 2 only.\n")
    w("| family | cells | onset − Gaussian (min … max) | CI inside ±0.05 | CI outside | median d_denom ratio vs Gaussian |")
    w("|---|---|---|---|---|---|")
    for f_, r in fam.iterrows():
        w(f"| {f_} | {int(r.n)} | {r.lo:+.3f} … {r.hi:+.3f} | {int(r.inside)} | {int(r.outside)} | {b3[f_]:.2f} |")
    w("")
    # Q4
    n2 = conv[conv.variant == "n2"]
    oth = conv[conv.variant != "n2"]
    w(f"**Q4 – uncertainty.** H4a (seed spread exceeds MC error): **{V['H4a']}** ({H['H4a']['share']:.0%} of "
      f"{H['H4a']['n']} headline points; median ratio {H['H4a']['median_sd_over_mcse']:.1f}). H4b (= test M13, doubling "
      f"M, n_est, s-nodes or x-nodes changes every TV by < max(3 SE, 1e-3)): **{V['H4b']}**. Doubling M, s-nodes or "
      f"x-nodes gives {int(oth.n_violations.sum())} violations (worst {oth.worst_ratio.max():.2f} of the tolerance); "
      f"doubling n_est gives {int(n2.n_violations.sum())} of {int(n2.n.sum())} (k = 8 and 32 only): the result depends "
      f"on the estimation sample beyond MC precision, consistent with H4a. All violations: "
      f"`results2/summary/convergence_violations.csv`.\n")
    # Q5
    a = pd.DataFrame(H["H5a"]["cells"])
    med = a.groupby("belief").ratio.median()
    parts = []
    for k_, side in (("H5b", 0), ("H5c", 0), ("H5d", 0)):
        parts.append(f"{k_} **{V[k_]}** ({H[k_]['significant']}/{H[k_]['n']} significant, "
                     f"{opposite(H[k_]['cells'], side)} significant in the opposite direction)")
    w(f"**Q5 – depth and training.** H5a (d_total grows from L = 1 to L = 4): **{V['H5a']}** "
      f"({H['H5a']['significant']}/{H['H5a']['n']}; {opposite(H['H5a']['cells'], 1)} cells significantly below 1). "
      f"Seed-median ratio d_total(4)/d_total(1): " + ", ".join(f"{b} {v:.2f}" for b, v in med.items()) +
      "; for S2 and S3c d_total at L = 4 is below its L = 1 value. "
      f"Training (H5b d_denom, H5c P(D<0), H5d end-to-end d_total on held-out beliefs): " + "; ".join(parts) +
      ". Figure G9 shows the flat-D control alongside.\n")

    w("## Limitations")
    w("- One neuron family (Legendre, m ≤ 6), exchangeable or LKJ dependence, k ≤ 32; networks only k ≤ 8, L ≤ 4, "
      "fixed a = 0.6, b = 0.5; training settings fixed in advance, not tuned.")
    w("- min D is an upper bound from a multi-start optimiser, so onsets are, if anything, late (conservative).")
    w("- d_denom is defined only while EXACT_UNCAL is; at high k and ρ_S the comparison is empty, not small.")
    w("- With n_est = 1e7 the TVs at k ≥ 8 move by a few per cent of their value when n_est doubles (H4b).")
    w("- Methods note (not deviations): during production D(y) was evaluated from row 0 only, all min-D searches of a job "
      "were stacked into one problem, and the Student-t CDF/quantile moved to the GPU; whole-job outputs agreed with the "
      "previous code to 1e-10 and test M7 checks the t functions against scipy. Ten t-copula slots that timed out before "
      "the fix were re-run; no result was produced by the old code.\n")
    w("## Deviations from the pre-registration")
    w(deviations + "\n")
    w("## Three talking points (measurements)")
    w(f"1. With a flat belief and the pair basis, d_denom reaches 1 % at ρ_S = {f3(g.loc[('SUM', 'pair', 2)].denom_1pct)} "
      f"for k = 2 and {f3(g.loc[('SUM', 'pair', 16)].denom_1pct)} for k = 16 (SUM); for k = 32 D turns negative first.")
    w(f"2. The ρ_S at which D first becomes negative falls from {f3(g.loc[('SUM', 'pair', 2)].neg_onset)} (k = 2) to "
      f"{f3(g.loc[('SUM', 'pair', 32)].neg_onset)} (k = 32, pair) and is 0 for the triple basis from k = 16: there, "
      f"E_q[N/D] is undefined while CONST_DENOM stays defined (E_q[D] = 1 under the flat belief).")
    w(f"3. Under the pre-registered settings, training did not reduce d_denom or P(D<0) in most cells, and in a "
      f"4-layer chain d_total decreased with depth (median ratio {med.get('S2', np.nan):.2f} for S2).")
    open(os.path.join(ROOT, "report2.md"), "w").write("\n".join(L) + "\n")

    pl = (f"**Podsumowanie (badanie skalowane).** Sprawdziłem numerycznie przybliżenie stałego mianownika "
          f"(E[N]/E[D] zamiast E[N/D]) w neuronie HCR dla k = 2–32 wejść, {n_jobs} zadań na GPU A100, hipotezy "
          f"zarejestrowane z góry. Przy płaskim przekonaniu i bazie par różnica TV osiąga 1 % przy ρ_S = "
          f"{f3(g.loc[('SUM', 'pair', 2)].denom_1pct).replace('.', ',')} (k = 2) i "
          f"{f3(g.loc[('SUM', 'pair', 16)].denom_1pct).replace('.', ',')} (k = 16). Gęstość D staje się ujemna od "
          f"ρ_S = {f3(g.loc[('SUM', 'pair', 2)].neg_onset).replace('.', ',')} (k = 2) do "
          f"{f3(g.loc[('SUM', 'pair', 32)].neg_onset).replace('.', ',')} (k = 32); wtedy dokładny iloraz jest "
          f"nieokreślony, a przybliżenie pozostaje określone. Wyniki zależą od rodziny kopuł (H3: nie potwierdzone). "
          f"Trening nie zmniejszył błędu w większości komórek, a w łańcuchu 4 neuronów błąd malał z głębokością. "
          f"Test zbieżności względem n_est nie przeszedł (szum estymacji). Pliki: report2.md, "
          f"figures2/summary_onepager2.png.")
    open(os.path.join(ROOT, "summary_PL2.md"), "w").write(pl + "\n")
    print("report2.md:", len(" ".join(L).split()), "words; summary_PL2.md:", len(pl.split()), "words")


if __name__ == "__main__":
    main()
